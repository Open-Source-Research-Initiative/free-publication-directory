// Optional rendered-directory check. Uses an existing Playwright installation.
const {chromium}=require(process.env.OSRI_PLAYWRIGHT_MODULE||'playwright');
const fs=require('fs');
const path=require('path');
const assert=require('assert/strict');
const crypto=require('crypto');
const root=path.resolve(__dirname,'..');
const output=path.join(root,'research','qa');
(async()=>{
  fs.mkdirSync(output,{recursive:true});
  const options={headless:true};
  if(process.env.OSRI_CHROMIUM)options.executablePath=process.env.OSRI_CHROMIUM;
  const browser=await chromium.launch(options);
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('file://'+path.join(root,'index.html'));
  const expected=await page.evaluate(()=>catalog.venues.filter(v=>v.route.eligibility==='verified_free'&&v.review.type==='peer_reviewed'&&v.submission_status!=='closed').length);
  assert.equal(await page.locator('.venue').count(),expected,'Default list must contain only verified free peer-reviewed routes without known closure.');
  await page.locator('.venue details').first().locator('summary').click();
  assert(await page.locator('.venue details').first().evaluate(e=>e.open));
  assert(await page.locator('.detail').first().getByRole('heading',{name:'Fee evidence',exact:true}).isVisible());
  await page.selectOption('#sort','difficulty');
  assert.match(await page.locator('#sort-note').textContent(),/Choose a research subfield/);
  const fields=await page.evaluate(()=>catalog.subfields.map(s=>s.id));
  for(const field of fields){
    await page.selectOption('#subfield',field);
    const wanted=await page.evaluate(f=>catalog.venues.filter(v=>Object.hasOwn(v.difficulty_by_subfield,f)&&v.route.eligibility==='verified_free'&&v.review.type==='peer_reviewed'&&v.submission_status!=='closed').length,field);
    assert.equal(await page.locator('.venue').count(),wanted,field+' count');
  }
  await page.selectOption('#subfield','public-policy');
  await page.selectOption('#sort','acceptance');
  assert.match(await page.locator('.venue h2').first().textContent(),/^Public Policy and Administration$/);
  assert.match(await page.locator('.venue .meta').nth(1).textContent(),/7.3%/,'The displayed selected metric must explain the acceptance sort.');
  await page.click('#reset-filters');
  await page.fill('#query','no-such-venue-000000');
  assert.equal(await page.locator('.venue').count(),0);
  assert(await page.getByRole('heading',{name:'No venues match these filters'}).isVisible());
  await page.click('#reset-filters');
  await page.selectOption('#eligibility','');
  await page.uncheck('#peer');
  await page.check('#closed');
  const total=await page.evaluate(()=>catalog.venues.length);
  assert.equal(await page.locator('.venue').count(),total);
  const closed=await page.evaluate(()=>catalog.venues.filter(v=>v.submission_status==='closed').map(v=>v.id));
  for(const id of closed)assert(await page.locator('[data-id="'+id+'"] .status').getByText('Submissions closed',{exact:true}).isVisible());
  await page.click('#reset-filters');
  await page.screenshot({path:path.join(output,'desktop.png'),fullPage:false});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile page must not overflow horizontally.');
  await page.selectOption('#subfield','informatics-computing');
  await page.selectOption('#sort','difficulty');
  await page.screenshot({path:path.join(output,'mobile.png'),fullPage:false});
  assert.equal(errors.length,0,errors.join('\n'));
  const digest=p=>crypto.createHash('sha256').update(fs.readFileSync(path.join(root,p))).digest('hex');
  const report={status:'pass',default_results:expected,total_venues:total,subfields_checked:fields.length,closed_venues_checked:closed.length,catalog_sha256:digest('data/venues.json'),html_sha256:digest('index.html'),checks:['default cost/review/availability gate','expandable fee evidence','cross-field ranking guard','all subfield filter counts','empty state','reset','all statuses and dissemination kinds','known closed labels','desktop rendering','mobile filtering and overflow','no browser script errors'],browser:'Playwright Chromium from existing installation; no Browser/IAB tool is available in this session',viewports:['1440x1100','390x844']};
  fs.writeFileSync(path.join(output,'browser-check.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report,null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
